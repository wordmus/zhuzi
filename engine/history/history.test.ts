// 运行：npx tsx engine/history/history.test.ts
import { isDeepStrictEqual as equal } from 'node:util';
import type { Fact } from '../types';
import { createHistory, loadHistory, type HistoryEvent, type HistoryMacro } from './index';

const failures: string[] = [];
const check = (ok: boolean, msg: string) => {
  console.log(`${ok ? '  ok ' : ' FAIL'}  ${msg}`);
  if (!ok) failures.push(msg);
};
const len = (s: string) => [...s].length;
const keys = ['minxin', 'grain', 'power', 'rites'] as const;
const kinds = ['war', 'reform', 'rite', 'scholar', 'omen', 'relief'];
const people = ['禾', '桑', '小石', '季', '田伯', '乡邻'];
const clamp = (n: number) => Math.max(0, Math.min(1, n));
const throws = (fn: () => unknown) => { try { fn(); return false; } catch { return true; } };
const table = loadHistory();
const { events, span, macro } = table;
const years = events.map(e => e.year);
const verified = events.filter(e => e.verified).length;
console.log(`\n== 历史长卷：${events.length} 件，前${-years[0]}—前${-years.at(-1)!}，跨度 ${years.at(-1)! - years[0]!} 年；已核验 ${verified}，待核 ${events.length - verified} ==`);
check(events.length >= 8 && years.at(-1)! - years[0]! >= 50, '至少八件，跨度至少五十年');
check(years[0] === span.from && years.at(-1) === span.to && span.from === -356 && span.to === -306, '事件实际覆盖前356—前306年');
check(years.every((y, i) => i === 0 || y >= years[i - 1]!), '年表按年份前进');
check(new Set(events.map(e => e.id)).size === events.length, '事件编号唯一');
check(events.every(e => e.source.title.length > 0 && /^https:\/\//.test(e.source.url ?? '')), '每件有书名篇年与真实来源链接');
check(events.every(e => typeof e.verified === 'boolean'), '每件明确写出核验状态（离线检查不替代读原文）');
check(events.every(e => kinds.includes(e.kind) && people.includes(e.enters.who)), '事件种类与入场人物合法');
check(events.every(e => len(e.text) <= 30 && len(e.enters.line) <= 18), '事件≤30字，进入个体的一句≤18字');
check(events.every(e => Object.entries(e.effects).every(([k, v]) => keys.includes(k as keyof HistoryMacro) && Number.isFinite(v) && Math.abs(v) <= 0.2)), '变化只用四个宏观量，且绝对值≤0.2');

console.log('\n== 跨章推进与写回 ==');
const h = createHistory({ events, startYear: span.from, macro });
check(equal(h.state(), { year: span.from, fired: [], macro }), '起点不暗中触发事件');
const first = h.advanceTo(span.from);
check(equal(first.map(e => e.id), ['pinglu-356']), '第一章在起始年也能收到当年事件');
const intermediate = h.advanceTo(-341);
check(equal(intermediate.map(e => e.year), [-353, -350, -348, -341]), '跨年依次收到桂陵、阡陌、朝周、马陵');
const expected = { ...macro };
for (const e of [...first, ...intermediate]) for (const k of keys) expected[k] = clamp(expected[k] + (e.effects[k] ?? 0));
check(equal(h.state().macro, expected), '事件逐条写入宏观量');
const entry = h.enter(intermediate[0]!);
check(equal(entry, { who: '禾', line: '魏军败了，粮还得交。', year: -353 }), '胜仗变成禾眼前的军粮要求');
const prior = h.ledger();
const beforeDecision = h.state();
const afterDecision = h.writeBack({ by: '禾', decision: '留下种粮，和乡邻分担征粮', delta: { grain: 0.03, minxin: 0.02 } });
check(afterDecision.macro.grain === beforeDecision.macro.grain + 0.03 && afterDecision.macro.minxin === beforeDecision.macro.minxin + 0.02, '禾留种粮使粮与民心改变');
const decision = h.ledger().at(-1)!;
check(decision.kind === 'decision' && decision.by === '禾' && decision.day === 15 && decision.text.includes('前341年'), '决定写入带年份和人物的事实');
check(equal(h.ledger().slice(0, prior.length), prior) && h.ledger().length === prior.length + 1, '写回只追加，不改历史事实');
const unchanged = h.state();
const savedLedger = h.ledger();
check(h.advanceTo(-341).length === 0 && h.advanceTo(-354).length === 0 && equal(h.state(), unchanged) && equal(h.ledger(), savedLedger), '重访与倒退不重复、不改状态和账本');
const rest = h.advanceTo(span.to);
check(rest.every((e, i) => i === 0 || e.year >= rest[i - 1]!.year) && h.state().fired.length === events.length, '到末章时所有事件各发生一次');
check(equal(h.ledger().slice(0, savedLedger.length), savedLedger), '跨章之后旧账本仍逐字保留');

console.log('\n== 边界、隔离与重开 ==');
const fixture: HistoryEvent = { ...events[0]!, id: 'limit', effects: { minxin: -0.2, grain: 0.2, power: 0.2, rites: -0.2 } };
const bounded = createHistory({ events: [fixture], startYear: -356, macro: { minxin: 0.01, grain: 0.99, power: 1, rites: 0 } });
bounded.advanceTo(-356);
check(equal(bounded.state().macro, { minxin: 0, grain: 1, power: 1, rites: 0 }), '事件把四个量夹在0到1');
bounded.writeBack({ by: '田伯', decision: '开仓', delta: { minxin: 5, grain: -5 } });
check(equal(bounded.state().macro, { minxin: 1, grain: 0, power: 1, rites: 0 }), '个体写回也不会越界');
const atEnd = createHistory({ events, startYear: span.to, macro });
check(atEnd.advanceTo(span.from).length === 0 && atEnd.state().year === span.to && atEnd.ledger().length === 0, '起点即末年：倒退安静返回空事件');

const input = structuredClone(events);
const ledgerInput: Fact[] = [{ id: 'earlier', day: 0, text: '旧章留种', kind: 'decision', by: '禾' }];
const isolated = createHistory({ events: input, startYear: span.from, macro, ledger: ledgerInput });
input[0]!.enters.line = '外部篡改';
ledgerInput[0]!.text = '外部篡改';
const eventView = isolated.events();
eventView[0]!.effects.grain = 100;
const stateView = isolated.state();
stateView.macro.grain = 100;
const factsView = isolated.ledger();
factsView[0]!.text = '外部篡改';
const delivered = isolated.advanceTo(span.from);
delivered[0]!.title = '外部篡改';
check(isolated.events()[0]!.enters.line !== '外部篡改' && isolated.ledger()[0]!.text === '旧章留种' && isolated.state().macro.grain === macro.grain && isolated.events()[0]!.title === events[0]!.title, '输入、事件、状态、返回事件和账本均隔离外部修改');
const loadedAgain = loadHistory();
loadedAgain.events[0]!.title = '外部篡改';
check(loadHistory().events[0]!.title === events[0]!.title, 'JSON每次加载独立副本');

const run = () => {
  const api = createHistory({ events: [...events].reverse(), startYear: span.from, macro });
  api.advanceTo(-341);
  api.writeBack({ by: '禾', decision: '留种粮', delta: { grain: 0.03 } });
  api.advanceTo(span.to);
  return { state: api.state(), ledger: api.ledger() };
};
check(equal(run(), run()), '同一输入的两次完整长卷，状态与账本深相等');
const saved = { state: h.state(), ledger: h.ledger() };
const resumed = createHistory({ events, startYear: saved.state.year, macro: saved.state.macro, ledger: saved.ledger });
check(equal(resumed.state(), saved.state) && resumed.advanceTo(span.to).length === 0 && equal(resumed.ledger(), saved.ledger), '同一存档重开，不重播末年事件、不再扣粮');
resumed.writeBack({ by: '小石', decision: '接过父亲的种粮', delta: { grain: 0.01 } });
check(new Set(resumed.ledger().map(f => f.id)).size === resumed.ledger().length && equal(resumed.ledger().slice(0, saved.ledger.length), saved.ledger), '重开后继续追加决定，编号不碰撞、旧事实不改');
const invalidBefore = resumed.state();
check(throws(() => resumed.writeBack({ by: '禾', decision: '未来的决定', delta: { grain: 0.1 }, year: -305 })) && equal(resumed.state(), invalidBefore), '拒绝未来写回，不跳过尚未发生的事件');
check(throws(() => resumed.writeBack({ by: '禾', decision: '坏数', delta: { grain: NaN } })) && equal(resumed.state(), invalidBefore), '拒绝非数值写回，状态仍完整');
check(throws(() => createHistory({ events: [fixture, fixture], startYear: -356 })), '重复编号在触发前就报错');
console.log(failures.length ? `\n${failures.length} 项失败` : '\n全部通过');
process.exitCode = failures.length ? 1 : 0;
