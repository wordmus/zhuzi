import assert from 'node:assert/strict';
import type { VisitRecord } from './context';
import { computeVisitChanges } from '../frameworks/vignette/visit-changes';

const first: VisitRecord = { n: 1, at: 1000, seed: 11, dwell: {} };
assert.deepEqual(computeVisitChanges(null, first), []);
console.log('PASS 首次来访 → 空变化');
const previous: VisitRecord = { ...first, dwell: { mentor: 40000, ticket: 0 }, skipped: ['ticket'] };
const current: VisitRecord = { ...first, n: 2, at: 2000 };
const snapshot = JSON.stringify([previous, current]);
const changes = computeVisitChanges(previous, current);
assert.ok(changes.length >= 1 && changes.length <= 2);
assert.match(changes[0]!.why, /visit.last.dwell\["mentor"\]=40000/);
assert.equal(changes[0]!.since, previous.at);
assert.equal(changes[0]!.visit, 2);
assert.ok(changes.every(c => [...c.attribution].length <= 18));
assert.deepEqual(computeVisitChanges(previous, current), changes);
assert.equal(JSON.stringify([previous, current]), snapshot);
console.log('PASS mentor 停 40s、跳过 ticket → 灯靠近，why 引用真实 dwell 字段');
console.log('PASS 同输入两次结果一致；输入未修改；归因 ≤18 字');
const second: VisitRecord = { ...previous, n: 2, at: 2000, changes };
const third = computeVisitChanges(second, { ...current, n: 3 });
assert.ok(third.length > 0);
assert.ok(third.every(c => !changes.some(p => p.place === c.place)));
assert.match(third[0]!.why, /visit.last.skipped.*ticket/);
const fourth = computeVisitChanges({ ...second, n: 3, changes: [...changes, ...third] }, { ...current, n: 4 });
assert.ok(fourth.every(c => !third.some(p => p.place === c.place)));
assert.equal(fourth.some(c => c.place === 'lamp'), false, '原处已合适，不假装又挪了一次灯');
console.log('PASS 下次换一处：年谱保留跳过票根的草稿；同处不连续变化');
assert.deepEqual(computeVisitChanges({ ...first, n: 2 }, { ...current, n: 3 }), []);
const legacy = computeVisitChanges({ ...first, longestPlace: '井边', longestPlaceMs: 40000 }, current);
assert.match(legacy[0]!.why, /longestPlace="井边"; longestPlaceMs=40000/);
assert.equal(computeVisitChanges({ ...first, skipped: ['ticket'] }, current)[0]?.place, 'chronicle');
console.log('PASS 旧记录兼容；无行为证据不编造；只跳过票根也有年谱留痕');
console.log('PASS visit-changes 6/6');
